def reads_as(name: str) -> str:
    """ "male", "female", "neutral" or "unknown", for one given name.

    Neutral is checked first: a name used across genders is not a man's name
    that happens to turn up in a woman's book.
    """
    key = (name or "").strip().rstrip(".").lower()
    if not key:
        return "unknown"
    if key in NEUTRAL:
        return "neutral"
    if key in MALE:
        return "male"
    if key in FEMALE:
        return "female"
    return "unknown"
